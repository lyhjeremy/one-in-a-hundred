"""One catalogue: data/metrics.json (hand-written) merged with
data/metrics_extra.json (metrics defined by the research loop, generated by
build_facts.py from pipeline/inbox/metrics/*.json). Every pipeline script
imports METRICS from here so the two files never drift apart."""
from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
_BASE = ROOT / "data" / "metrics.json"
_EXTRA = ROOT / "data" / "metrics_extra.json"

EXTRA_FAMILY = {"more": {"label": "More measures (researched)", "order": 9}}


def load() -> dict:
    cat = json.loads(_BASE.read_text())
    cat["families"].update(EXTRA_FAMILY)
    if _EXTRA.exists():
        extra = json.loads(_EXTRA.read_text())
        for mid, m in extra.get("metrics", {}).items():
            cat["metrics"].setdefault(mid, {**m, "family": m.get("family", "more")})
        cat["activities"].update(extra.get("activities", {}))
    return cat


CATALOG = load()
METRICS = CATALOG["metrics"]
